#!/usr/bin/env python3
"""Regenerates the baseline of known PMD, Checkstyle and SpotBugs findings.

The build fails on findings that are not in the baseline (see analysis.fail in parent/pom.xml).
Run this script after fixing findings, so that the fixed ones leave the baseline, and commit the
three files it writes next to it. Do not run it to hide new findings.

    python3 parent/analysis/update-baseline.py                  # builds with maven, then writes the files
    python3 parent/analysis/update-baseline.py REPORT_DIR ...   # only reads the reports in the directories

The build runs without the baseline and without the tests, so that the reports hold every finding.
A report directory is the target directory of a module (pmd.xml, checkstyle-result.xml and
spotbugsXml.xml).

Only pass report directories of a build that ran without the baseline, like the one in build(): the
reports of a normal build leave out the Checkstyle and SpotBugs findings that are in the baseline, so
the new files would hold only the findings that are not in it. The script stops, without writing a
file, when a report directory misses one of the three reports.
"""
import glob
import os
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
PARENT = os.path.dirname(HERE)

PMD_FILE = "pmd-baseline.properties"
CHECKSTYLE_FILE = "checkstyle-suppressions.xml"
SPOTBUGS_FILE = "spotbugs-exclude.xml"


SUPPRESSIONS_HEAD = ('<?xml version="1.0"?>\n'
                     '<!DOCTYPE suppressions PUBLIC "-//Checkstyle//DTD SuppressionFilter Configuration 1.2//EN"\n'
                     '    "https://checkstyle.org/dtds/suppressions_1_2.dtd">\n')


def build():
    """Runs the analysis without the baseline: the baseline directory holds empty files."""
    empty = tempfile.mkdtemp(prefix="empty-baseline-")
    for name, content in ((PMD_FILE, ""),
                          (CHECKSTYLE_FILE, SUPPRESSIONS_HEAD + "<suppressions/>\n"),
                          (SPOTBUGS_FILE, '<?xml version="1.0"?>\n<FindBugsFilter/>\n')):
        with open(os.path.join(empty, name), "w") as f:
            f.write(content)
    subprocess.run(["mvn", "-B", "-f", os.path.join(PARENT, "pom.xml"), "clean", "verify",
                    "-DskipTests", "-Danalysis.fail=false", "-Danalysis.baseline=" + empty],
                   check=True)


REPORTS = ("pmd.xml", "checkstyle-result.xml", "spotbugsXml.xml")


def check_reports(dirs):
    """Stops before anything is written when the reports are missing or incomplete."""
    if not dirs:
        sys.exit("no report directories found: did the build run?")
    missing = [os.path.join(d, r) for d in dirs for r in REPORTS if not os.path.isfile(os.path.join(d, r))]
    if missing:
        sys.exit("missing reports, the baseline files are not changed:\n  " + "\n  ".join(missing))


def report_dirs():
    return sorted(glob.glob(os.path.join(PARENT, "bundles", "*", "target")) +
                  glob.glob(os.path.join(PARENT, "examples", "*", "target")))


def pmd(dirs):
    rules = defaultdict(set)
    for d in dirs:
        path = os.path.join(d, "pmd.xml")
        file_name = None
        for violation in ET.parse(path).getroot().iter():
            tag = violation.tag.rsplit("}", 1)[-1]
            if tag == "file":
                file_name = violation.get("name")
            if tag != "violation":
                continue
            package, cls = violation.get("package"), violation.get("class")
            if not cls:
                # anonymous classes have no class name and cannot be listed: fix these findings
                sys.exit("PMD finding without a class, fix it: %s:%s %s" % (
                    file_name, violation.get("beginline"), violation.get("rule")))
            rules[(package + "." if package else "") + cls].add(violation.get("rule"))
    return "".join("%s=%s\n" % (cls, ",".join(sorted(r))) for cls, r in sorted(rules.items()))


def checkstyle(dirs):
    pairs = set()
    for d in dirs:
        path = os.path.join(d, "checkstyle-result.xml")
        for file in ET.parse(path).getroot().iter("file"):
            name = file.get("name").replace(os.sep, "/")
            source = name.rsplit("/src/", 1)[-1] if "/src/" in name else name
            for error in file.iter("error"):
                pairs.add((source, error.get("source")))
    out = [SUPPRESSIONS_HEAD.rstrip("\n"),
           "<!-- Known findings, one entry per file and check. Generated by update-baseline.py. -->",
           "<suppressions>"]
    for source, check in sorted(pairs):
        files = "[\\\\/]" + "[\\\\/]".join(re.escape(part) for part in source.split("/")) + "$"
        if "." in check:
            out.append('  <suppress files="%s" checks="\\.%s$"/>' % (files, check.rsplit(".", 1)[-1]))
        else:
            # a check with an id (as in the Google style) is reported by the id, without a package
            out.append('  <suppress files="%s" id="%s"/>' % (files, check))
    out.append("</suppressions>")
    return "\n".join(out) + "\n"


def spotbugs(dirs):
    pairs = set()
    for d in dirs:
        path = os.path.join(d, "spotbugsXml.xml")
        for bug in ET.parse(path).getroot().iter("BugInstance"):
            cls = bug.find("Class")
            if cls is not None:
                pairs.add((cls.get("classname"), bug.get("type")))
    out = ['<?xml version="1.0"?>',
           "<!-- Known findings, one entry per class and bug pattern. Generated by update-baseline.py. -->",
           "<FindBugsFilter>"]
    for cls, bug in sorted(pairs):
        out.append('  <Match><Class name="%s"/><Bug pattern="%s"/></Match>' % (cls, bug))
    out.append("</FindBugsFilter>")
    return "\n".join(out) + "\n", len(pairs)


def main(args):
    if not args:
        build()
    dirs = args or report_dirs()
    check_reports(dirs)
    spotbugs_xml, spotbugs_count = spotbugs(dirs)
    files = ((PMD_FILE, pmd(dirs)), (CHECKSTYLE_FILE, checkstyle(dirs)), (SPOTBUGS_FILE, spotbugs_xml))
    for name, content in files:
        with open(os.path.join(HERE, name), "w") as f:
            f.write(content)
        print("wrote", os.path.join(HERE, name))


if __name__ == "__main__":
    main(sys.argv[1:])
